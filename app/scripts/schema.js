const snake = (str) => str.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`);
let schema =
  'generator client {\n  provider = "prisma-client-js"\n}\ndatasource db {\n  provider = "postgresql"\n  url = env("DATABASE_URL")\n  directUrl = env("MIGRATION_DATABASE_URL")\n}\n';
Object.entries(models).forEach(([name, fields], i) => {
  schema += `\nmodel ${name} {\n`;
  for (let field of fields) {
    if (field === "teamId_PLACEHOLDER") continue;
    if (name === "Topic" && field.startsWith("teamId ")) field += " @unique";
    if (!field.startsWith("@@")) {
      const key = field.split(" ")[0];
      if (snake(key) !== key) field += ` @map("${snake(key)}")`;
    }
    schema += `  ${field}\n`;
  }
  schema += `  @@map("${tables[i]}")\n}\n`;
});
writeFileSync("app/server/prisma/schema.prisma", schema);
